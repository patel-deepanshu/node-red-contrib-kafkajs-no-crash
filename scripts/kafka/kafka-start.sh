#!/usr/bin/env bash
# Start a single-node KRaft (no ZooKeeper) Kafka broker+controller with two listeners:
#   PLAINTEXT       on $KAFKA_HOST:$KAFKA_PLAINTEXT_PORT (default 127.0.0.1:19092)
#   SASL_PLAINTEXT  on $KAFKA_HOST:$KAFKA_SASL_PORT      (default 127.0.0.1:19093)
#                   mechanisms PLAIN, SCRAM-SHA-256, SCRAM-SHA-512
#                   users admin/admin-secret and alice/alice-secret (all mechanisms)
#
# Idempotent: storage is formatted only once (marker: $KAFKA_DATA_DIR/meta.properties);
# if the broker is already running it just waits until it is ready.
#
# Usage: KAFKA_HOME=/path/to/kafka_2.13-3.9.1 ./kafka-start.sh
set -euo pipefail
# shellcheck source=kafka-env.sh
. "$(dirname "${BASH_SOURCE[0]}")/kafka-env.sh"

mkdir -p "$KAFKA_CONF_DIR" "$KAFKA_DATA_DIR" "$KAFKA_LOG_DIR"

if pid="$(kafka_pid)"; then
  echo "kafka-start: already running (pid $pid), waiting for readiness"
  exec "$(dirname "${BASH_SOURCE[0]}")/kafka-wait-ready.sh"
fi

for port in "$KAFKA_PLAINTEXT_PORT" "$KAFKA_SASL_PORT" "$KAFKA_CONTROLLER_PORT"; do
  if kafka_port_open "$KAFKA_HOST" "$port"; then
    echo "kafka-start: port $KAFKA_HOST:$port is already in use by another process" >&2
    exit 1
  fi
done

# ---------------------------------------------------------------- config files
# Regenerated on every start so env overrides (ports, users) always apply.
plain_users="user_${KAFKA_ADMIN_USER}=\"${KAFKA_ADMIN_PASSWORD}\" user_${KAFKA_USER}=\"${KAFKA_PASSWORD}\""

cat >"$KAFKA_SERVER_PROPS" <<EOF
# Generated by kafka-start.sh - do not edit, edit the script / env vars instead.
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@${KAFKA_HOST}:${KAFKA_CONTROLLER_PORT}
controller.listener.names=CONTROLLER

listeners=PLAINTEXT://${KAFKA_HOST}:${KAFKA_PLAINTEXT_PORT},SASL_PLAINTEXT://${KAFKA_HOST}:${KAFKA_SASL_PORT},CONTROLLER://${KAFKA_HOST}:${KAFKA_CONTROLLER_PORT}
advertised.listeners=PLAINTEXT://${KAFKA_HOST}:${KAFKA_PLAINTEXT_PORT},SASL_PLAINTEXT://${KAFKA_HOST}:${KAFKA_SASL_PORT}
listener.security.protocol.map=CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT,SASL_PLAINTEXT:SASL_PLAINTEXT
inter.broker.listener.name=PLAINTEXT

# SASL on the SASL_PLAINTEXT listener
sasl.enabled.mechanisms=PLAIN,SCRAM-SHA-256,SCRAM-SHA-512
listener.name.sasl_plaintext.sasl.enabled.mechanisms=PLAIN,SCRAM-SHA-256,SCRAM-SHA-512
listener.name.sasl_plaintext.plain.sasl.jaas.config=org.apache.kafka.common.security.plain.PlainLoginModule required username="${KAFKA_ADMIN_USER}" password="${KAFKA_ADMIN_PASSWORD}" ${plain_users};
listener.name.sasl_plaintext.scram-sha-256.sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required;
listener.name.sasl_plaintext.scram-sha-512.sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required;

log.dirs=${KAFKA_DATA_DIR}
num.partitions=${KAFKA_NUM_PARTITIONS}
auto.create.topics.enable=${KAFKA_AUTO_CREATE_TOPICS}
offsets.topic.replication.factor=1
offsets.topic.num.partitions=3
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1
default.replication.factor=1
min.insync.replicas=1
group.initial.rebalance.delay.ms=0
log.retention.hours=24
log.segment.bytes=16777216
num.network.threads=2
num.io.threads=4
EOF

cat >"$KAFKA_CLIENT_PLAINTEXT_PROPS" <<EOF
security.protocol=PLAINTEXT
EOF
cat >"$KAFKA_CLIENT_SASL_PLAIN_PROPS" <<EOF
security.protocol=SASL_PLAINTEXT
sasl.mechanism=PLAIN
sasl.jaas.config=org.apache.kafka.common.security.plain.PlainLoginModule required username="${KAFKA_ADMIN_USER}" password="${KAFKA_ADMIN_PASSWORD}";
EOF
cat >"$KAFKA_CLIENT_SCRAM256_PROPS" <<EOF
security.protocol=SASL_PLAINTEXT
sasl.mechanism=SCRAM-SHA-256
sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required username="${KAFKA_ADMIN_USER}" password="${KAFKA_ADMIN_PASSWORD}";
EOF
cat >"$KAFKA_CLIENT_SCRAM512_PROPS" <<EOF
security.protocol=SASL_PLAINTEXT
sasl.mechanism=SCRAM-SHA-512
sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required username="${KAFKA_ADMIN_USER}" password="${KAFKA_ADMIN_PASSWORD}";
EOF

# ---------------------------------------------------------------- format once
if [ ! -f "$KAFKA_DATA_DIR/meta.properties" ]; then
  cluster_id="$(kafka_cli kafka-storage.sh random-uuid)"
  echo "kafka-start: formatting storage in $KAFKA_DATA_DIR (cluster id $cluster_id) with SCRAM users"
  scram_args=()
  for mech in SCRAM-SHA-256 SCRAM-SHA-512; do
    scram_args+=(--add-scram "${mech}=[name=${KAFKA_ADMIN_USER},password=${KAFKA_ADMIN_PASSWORD}]")
    scram_args+=(--add-scram "${mech}=[name=${KAFKA_USER},password=${KAFKA_PASSWORD}]")
  done
  kafka_cli kafka-storage.sh format --ignore-formatted -t "$cluster_id" -c "$KAFKA_SERVER_PROPS" "${scram_args[@]}"
  echo "$cluster_id" >"$KAFKA_BASE_DIR/cluster.id"
else
  echo "kafka-start: storage already formatted ($(grep cluster.id "$KAFKA_DATA_DIR/meta.properties"))"
fi

# ---------------------------------------------------------------- launch
echo "kafka-start: starting broker (logs: $KAFKA_LOG_DIR/server.out)"
# kafka-server-start.sh exec's kafka-run-class.sh which exec's java, so $! is the JVM pid.
nohup "$KAFKA_HOME/bin/kafka-server-start.sh" "$KAFKA_SERVER_PROPS" \
  >>"$KAFKA_LOG_DIR/server.out" 2>&1 </dev/null &
echo $! >"$KAFKA_PID_FILE"
echo "kafka-start: pid $(cat "$KAFKA_PID_FILE")"

exec "$(dirname "${BASH_SOURCE[0]}")/kafka-wait-ready.sh"
